-- One-owner product catalog for SoukLink Store.

-- The UUID is not a password or secret. It avoids publishing the admin email
-- in the website's JavaScript and ties write access to one exact Auth user.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric(10, 2) not null check (price >= 0),
  old_price numeric(10, 2),
  emoji text not null default '📦',
  image text not null,
  tone text not null default 'sage',
  badge text not null default 'Sélection',
  rating text not null default 'À découvrir',
  note text not null default 'Prix indicatif · disponibilité à confirmer',
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;

grant select on public.products to anon, authenticated;
grant insert, delete on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

drop policy if exists "Anyone can view products" on public.products;
create policy "Anyone can view products"
  on public.products for select
  to anon, authenticated
  using (true);

drop policy if exists "Only the site owner can add products" on public.products;
create policy "Only the site owner can add products"
  on public.products for insert
  to authenticated
  with check (auth.uid() = '5fa6fa95-8faf-465a-8ad7-7eea347e3026'::uuid);

drop policy if exists "Only the site owner can delete products" on public.products;
create policy "Only the site owner can delete products"
  on public.products for delete
  to authenticated
  using (auth.uid() = '5fa6fa95-8faf-465a-8ad7-7eea347e3026'::uuid);
